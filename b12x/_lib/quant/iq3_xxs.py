@cache
def iq3_xxs_grid_cpu():
    return torch.tensor(list(_GRID), dtype=torch.uint8).reshape(256, 4)


_DEVICE_TABLES = {}


def iq3_xxs_execution_lut(device, *, prepare=False):
    device = torch.device(device)
    if device.type == "cuda" and device.index is None:
        device = torch.device("cuda", torch.cuda.current_device())
    if device not in _DEVICE_TABLES:
        if not prepare:
            raise RuntimeError("IQ3_XXS lookup table must be prepared before replay")
        _DEVICE_TABLES[device] = iq3_xxs_grid_cpu().to(
            device=device, dtype=torch.bfloat16
        )
    return _DEVICE_TABLES[device]
